// Vectorizes the official ArmeTec logo PNGs (public/brand) into SVG paths
// used by the 3D extruded symbol and the masked wordmark reveal.
// Run: npm run brand   (outputs src/config/brand-paths.generated.ts)
import potrace from 'potrace';
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const tmp = path.join(root, 'out', 'trace');
fs.mkdirSync(tmp, {recursive: true});

// Prepare black-on-white bitmaps with python/Pillow (alpha -> luminance)
execFileSync('python3', ['-c', `
from PIL import Image
import sys
def prep(src, box, dst):
    im = Image.open(src).convert('RGBA')
    if box: im = im.crop(box)
    a = im.split()[3]
    bw = Image.eval(a, lambda v: 255 - v).convert('L')
    bw.save(dst)
    print(dst, bw.size)
prep('${root}/public/brand/armetec-symbol.png', (198, 201, 1609, 1606), '${tmp}/symbol.png')
prep('${root}/public/brand/armetec-logo-full.png', (318, 225, 866, 367), '${tmp}/arme.png')
prep('${root}/public/brand/armetec-logo-full.png', (866, 225, 1180, 367), '${tmp}/tec.png')
`], {stdio: 'inherit'});

const trace = (file) =>
  new Promise((resolve, reject) => {
    potrace.trace(file, {threshold: 128, turdSize: 20, optTolerance: 0.2}, (err, svg) => {
      if (err) return reject(err);
      const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
      const vb = svg.match(/width="(\d+)" height="(\d+)"/);
      resolve({d, width: Number(vb[1]), height: Number(vb[2])});
    });
  });

const symbol = await trace(`${tmp}/symbol.png`);
const arme = await trace(`${tmp}/arme.png`);
const tec = await trace(`${tmp}/tec.png`);

const out = `// AUTO-GENERATED by scripts/trace-logo.mjs from the official logo PNGs. Do not edit.
export const SYMBOL_PATH = ${JSON.stringify(symbol)} as const;
export const WORDMARK_ARME_PATH = ${JSON.stringify(arme)} as const;
export const WORDMARK_TEC_PATH = ${JSON.stringify(tec)} as const;
`;
fs.mkdirSync(path.join(root, 'src/config'), {recursive: true});
fs.writeFileSync(path.join(root, 'src/config/brand-paths.generated.ts'), out);
console.log('symbol', symbol.d.length, 'arme', arme.d.length, 'tec', tec.d.length);
